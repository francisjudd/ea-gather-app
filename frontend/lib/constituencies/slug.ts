// Same slug rules as scripts/export-constituencies.mjs: accents stripped, "&" becomes "and".
export function slugifyConstituency(name: string): string {
  return name
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}
