"""Convert data-source/combined.db (SQLite) into a Postgres SQL script for Supabase.

Usage (from the repo root):
    python3 backend/scripts/import_combined_db.py > /tmp/combined.sql
    psql "$DATABASE_URL" -v ON_ERROR_STOP=1 --single-transaction -f /tmp/combined.sql

Pass --replace to drop the existing tables first. Without it the script fails
if the tables already exist, so data edited in Supabase is never overwritten
by accident.
"""

import argparse
import sqlite3
import sys
from pathlib import Path

DEFAULT_DB = Path(__file__).resolve().parents[2] / "data-source" / "combined.db"

SCHEMA = """
create table postcodes (
    postcode            text primary key,
    found               boolean,
    lat                 double precision,
    lng                 double precision,
    constituency        text,
    constituency_code   text
);

create table outcodes (
    outcode             text primary key,
    found               boolean,
    lat                 double precision,
    lng                 double precision
);

create table categories (
    id                  bigint generated by default as identity primary key,
    name                text not null unique,
    created_at          timestamptz not null default now(),
    updated_at          timestamptz not null default now()
);

create table services (
    id                  bigint generated by default as identity primary key,
    category_id         bigint references categories(id),
    source              text,
    source_id           text,
    name                text,
    address             text,
    postcode            text,
    lat                 double precision,
    lng                 double precision,
    website             text,
    phone               text,
    email               text,
    constituency        text,
    constituency_code   text,
    charity_number      text,
    partner_church      text,
    -- Impact figures, entered by hand; combine.py never changes them
    people_helped       integer check (people_helped >= 0),
    financial_value_gbp double precision check (financial_value_gbp >= 0),
    volunteer_hours     double precision check (volunteer_hours >= 0),
    created_at          timestamptz not null default now(),
    updated_at          timestamptz not null default now(),
    unique (source, source_id)
);

create table churches (
    id                  bigint generated by default as identity primary key,
    slug                text unique,
    name                text,
    denomination        text,
    membership_id       bigint,
    address             text,
    postcode            text,
    lat                 double precision,
    lng                 double precision,
    website             text,
    phone               text,
    constituency        text,
    constituency_code   text,
    created_at          timestamptz not null default now(),
    updated_at          timestamptz not null default now()
);

create table church_services (
    church_id           bigint references churches(id),
    service_id          bigint references services(id),
    match_type          text,
    primary key (church_id, service_id)
);
"""

POST_LOAD = """
create index church_services_service on church_services(service_id);
create index services_category on services(category_id);
create index services_postcode on services(postcode);
create index services_constituency on services(constituency);
create index churches_postcode on churches(postcode);
create index churches_constituency_code on churches(constituency_code);

-- Identity columns must continue after the imported ids.
select setval(pg_get_serial_sequence('categories', 'id'), (select max(id) from categories));
select setval(pg_get_serial_sequence('services', 'id'), (select max(id) from services));
select setval(pg_get_serial_sequence('churches', 'id'), (select max(id) from churches));

create or replace function set_updated_at() returns trigger language plpgsql as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

create trigger categories_updated_at before update on categories
    for each row execute function set_updated_at();
create trigger services_updated_at before update on services
    for each row execute function set_updated_at();
create trigger churches_updated_at before update on churches
    for each row execute function set_updated_at();

create view church_service_details with (security_invoker = true) as
    select c.id as church_id, c.name as church_name, c.denomination,
           c.address as church_address, c.postcode as church_postcode,
           s.id as service_id, cat.name as category, s.name as service_name,
           s.address as service_address, s.website, s.phone, s.email,
           s.people_helped, s.financial_value_gbp, s.volunteer_hours,
           cs.match_type
    from church_services cs
    join churches c on c.id = cs.church_id
    join services s on s.id = cs.service_id
    left join categories cat on cat.id = s.category_id;

create view church_service_summary with (security_invoker = true) as
    select c.id as church_id, c.name as church_name, c.denomination,
           c.address as church_address, c.postcode as church_postcode,
           c.constituency, count(*) as service_count,
           string_agg(distinct cat.name, ',') as categories,
           sum(s.people_helped) as people_helped,
           sum(s.financial_value_gbp) as financial_value_gbp,
           sum(s.volunteer_hours) as volunteer_hours
    from church_services cs
    join churches c on c.id = cs.church_id
    join services s on s.id = cs.service_id
    left join categories cat on cat.id = s.category_id
    group by c.id;

-- RLS on with no policies: only the backend (service role / postgres) can read or write.
alter table postcodes enable row level security;
alter table outcodes enable row level security;
alter table categories enable row level security;
alter table services enable row level security;
alter table churches enable row level security;
alter table church_services enable row level security;
"""

DROP = """
drop view if exists church_service_summary, church_service_details;
drop table if exists church_services, churches, services, categories, outcodes, postcodes cascade;
drop function if exists set_updated_at();
"""

# Load order respects foreign keys.
TABLES = ["postcodes", "outcodes", "categories", "services", "churches", "church_services"]
BOOLEAN_COLUMNS = {("postcodes", "found"), ("outcodes", "found")}


def copy_value(table: str, column: str, value) -> str:
    if value is None:
        return r"\N"
    if (table, column) in BOOLEAN_COLUMNS:
        return "t" if value else "f"
    if isinstance(value, float):
        return repr(value)
    text = str(value)
    return (
        text.replace("\\", "\\\\")
        .replace("\t", "\\t")
        .replace("\n", "\\n")
        .replace("\r", "\\r")
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--db", type=Path, default=DEFAULT_DB)
    parser.add_argument("--replace", action="store_true", help="drop existing tables first")
    args = parser.parse_args()

    source = sqlite3.connect(f"file:{args.db}?mode=ro", uri=True)
    out = sys.stdout

    if args.replace:
        out.write(DROP)
    out.write(SCHEMA)

    for table in TABLES:
        cursor = source.execute(f"select * from {table}")
        columns = [d[0] for d in cursor.description]
        out.write(f"\ncopy {table} ({', '.join(columns)}) from stdin;\n")
        for row in cursor:
            out.write("\t".join(copy_value(table, c, v) for c, v in zip(columns, row)) + "\n")
        out.write("\\.\n")

    out.write(POST_LOAD)


if __name__ == "__main__":
    main()
